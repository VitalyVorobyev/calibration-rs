//! Render the dataset-manifest JSON Schema as the book's field reference.
//!
//! The reference page (`book/src/manifest_reference.md`) is generated from the
//! same schema the app's manifest form reads, so the documentation cannot
//! drift from the Rust types: `cargo xtask emit-schemas --check` fails when
//! the page is out of date.
//!
//! The renderer handles exactly the shapes `schemars` produces for
//! `DatasetSpec`: objects with `properties`, string enumerations (`oneOf` of
//! `const`s), tagged unions (`oneOf` of objects with a `kind` constant) and
//! `$ref`s, possibly wrapped in `anyOf [.., null]`.

use serde_json::Value;
use std::collections::BTreeSet;
use std::fmt::Write as _;

/// Render `schema` (the `DatasetSpec` schema) as a Markdown reference page.
pub fn render(schema: &Value) -> String {
    let defs = schema
        .get("$defs")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();

    // Definitions in the order the manifest first mentions them, so the page
    // reads from the top-level fields downwards.
    let mut order: Vec<String> = Vec::new();
    let mut seen = BTreeSet::new();
    visit_refs(schema, &defs, &mut order, &mut seen);
    for name in defs.keys() {
        if seen.insert(name.clone()) {
            order.push(name.clone());
        }
    }

    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("## DatasetSpec\n\n");
    render_definition(&mut out, schema);
    for name in &order {
        let _ = writeln!(out, "## {name}\n");
        render_definition(&mut out, &defs[name]);
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

const HEADER: &str = "\
# Manifest Field Reference

<!-- Generated by `cargo xtask emit-schemas` from the `DatasetSpec` JSON Schema. Do not edit. -->

Every field of the dataset manifest, generated from its JSON Schema. The prose \
chapter [The Dataset Manifest](manifest.md) explains how the pieces fit \
together; this page is the exhaustive list. The schema itself is \
`app/src/schemas/dataset_spec.json` in the repository, and the desktop app \
builds its manifest form from it.

Paths in a manifest are relative to the directory that holds it unless they \
are absolute. A field marked *required* has no default and must be present; \
an optional field may be omitted.

";

/// Depth-first walk collecting the `$defs` a schema refers to, in the order of
/// first mention.
fn visit_refs(
    node: &Value,
    defs: &serde_json::Map<String, Value>,
    order: &mut Vec<String>,
    seen: &mut BTreeSet<String>,
) {
    match node {
        Value::Object(map) => {
            if let Some(name) = map.get("$ref").and_then(Value::as_str).and_then(ref_name)
                && seen.insert(name.to_string())
            {
                order.push(name.to_string());
                if let Some(def) = defs.get(name) {
                    visit_refs(def, defs, order, seen);
                }
            }
            // Properties in the order the table shows them.
            if let Some(props) = map.get("properties").and_then(Value::as_object) {
                for key in property_order(map, props) {
                    visit_refs(&props[&key], defs, order, seen);
                }
            }
            for key in ["anyOf", "oneOf", "items"] {
                if let Some(child) = map.get(key) {
                    visit_refs(child, defs, order, seen);
                }
            }
        }
        Value::Array(items) => {
            for item in items {
                visit_refs(item, defs, order, seen);
            }
        }
        _ => {}
    }
}

fn ref_name(reference: &str) -> Option<&str> {
    reference.strip_prefix("#/$defs/")
}

/// Required properties first, then the optional ones, each group sorted by name.
fn property_order(
    object: &serde_json::Map<String, Value>,
    props: &serde_json::Map<String, Value>,
) -> Vec<String> {
    let required = required_set(object);
    let mut keys: Vec<String> = props.keys().cloned().collect();
    keys.sort_by_key(|k| (!required.contains(k), k.clone()));
    keys
}

fn required_set(object: &serde_json::Map<String, Value>) -> BTreeSet<String> {
    object
        .get("required")
        .and_then(Value::as_array)
        .map(|r| {
            r.iter()
                .filter_map(Value::as_str)
                .map(String::from)
                .collect()
        })
        .unwrap_or_default()
}

fn render_definition(out: &mut String, def: &Value) {
    if let Some(text) = def.get("description").and_then(Value::as_str) {
        let _ = writeln!(out, "{}\n", paragraph(text));
    }
    if def.get("properties").is_some() {
        render_object(out, def, None);
        return;
    }
    let Some(variants) = def.get("oneOf").and_then(Value::as_array) else {
        return;
    };
    if variants.iter().all(|v| v.get("const").is_some()) {
        out.push_str("| Value | Description |\n|---|---|\n");
        for variant in variants {
            let value = variant["const"].as_str().unwrap_or_default();
            let _ = writeln!(out, "| `{value}` | {} |", cell(description(variant)));
        }
        out.push('\n');
    } else {
        out.push_str("Tagged on `kind`; the fields depend on the variant.\n\n");
        for variant in variants {
            let kind = variant["properties"]["kind"]["const"]
                .as_str()
                .unwrap_or_default();
            let _ = writeln!(
                out,
                "**`kind = \"{kind}\"`**: {}\n",
                paragraph(description(variant))
            );
            render_object(out, variant, Some("kind"));
        }
    }
}

/// A table of an object schema's properties, skipping `skip` (a tag).
fn render_object(out: &mut String, object: &Value, skip: Option<&str>) {
    let Some(map) = object.as_object() else {
        return;
    };
    let Some(props) = map.get("properties").and_then(Value::as_object) else {
        return;
    };
    let required = required_set(map);
    let keys: Vec<String> = property_order(map, props)
        .into_iter()
        .filter(|k| Some(k.as_str()) != skip)
        .collect();
    if keys.is_empty() {
        return;
    }
    let any_default = keys.iter().any(|k| props[k].get("default").is_some());

    out.push_str("| Field | Type | Required |");
    out.push_str(if any_default { " Default |" } else { "" });
    out.push_str(" Description |\n|---|---|---|");
    out.push_str(if any_default { "---|" } else { "" });
    out.push_str("---|\n");
    for key in &keys {
        let prop = &props[key];
        let default = prop
            .get("default")
            .map(|d| format!(" `{d}` |"))
            .unwrap_or_else(|| {
                if any_default {
                    " |".into()
                } else {
                    String::new()
                }
            });
        let _ = writeln!(
            out,
            "| `{key}` | {} | {} |{default} {} |",
            type_string(prop),
            if required.contains(key) { "yes" } else { "no" },
            cell(description(prop)),
        );
    }
    out.push('\n');
    if map.get("additionalProperties") == Some(&Value::Bool(false)) {
        out.push_str("Unknown fields are rejected.\n\n");
    }
}

fn description(node: &Value) -> &str {
    node.get("description")
        .and_then(Value::as_str)
        .unwrap_or("")
}

/// A short human type for a property schema.
fn type_string(node: &Value) -> String {
    if let Some(name) = node.get("$ref").and_then(Value::as_str).and_then(ref_name) {
        return format!("[{name}](#{})", name.to_lowercase());
    }
    if let Some(any) = node.get("anyOf").and_then(Value::as_array) {
        let parts: Vec<String> = any
            .iter()
            .filter(|v| v.get("type") != Some(&Value::String("null".into())))
            .map(type_string)
            .collect();
        return parts.join(" or ");
    }
    if let Some(constant) = node.get("const").and_then(Value::as_str) {
        return format!("`\"{constant}\"`");
    }
    let kinds: Vec<&str> = match node.get("type") {
        Some(Value::String(t)) => vec![t.as_str()],
        Some(Value::Array(ts)) => ts.iter().filter_map(Value::as_str).collect(),
        _ => vec![],
    };
    let kinds: Vec<&str> = kinds.into_iter().filter(|t| *t != "null").collect();
    match kinds.as_slice() {
        ["array"] => {
            let items = node.get("items").map(type_string).unwrap_or_default();
            match node.get("minItems").and_then(Value::as_u64) {
                Some(n) if node.get("maxItems").and_then(Value::as_u64) == Some(n) => {
                    format!("array of {n} {items}")
                }
                _ => format!("array of {items}"),
            }
        }
        [one] => (*one).to_string(),
        [] => "any".to_string(),
        many => many.join(" or "),
    }
}

/// A description as one Markdown paragraph (soft-wrapped lines joined).
fn paragraph(text: &str) -> String {
    text.split("\n\n")
        .map(|p| p.split('\n').collect::<Vec<_>>().join(" "))
        .collect::<Vec<_>>()
        .join("\n\n")
}

/// A description inside a table cell: one line, `|` escaped, paragraphs
/// separated by a line break.
fn cell(text: &str) -> String {
    paragraph(text)
        .replace("\n\n", "<br><br>")
        .replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn renders_objects_enums_and_tagged_unions() {
        let schema = json!({
            "description": "Top.",
            "type": "object",
            "additionalProperties": false,
            "required": ["mode"],
            "properties": {
                "mode": {"$ref": "#/$defs/Mode", "description": "How."},
                "target": {"anyOf": [{"$ref": "#/$defs/Target"}, {"type": "null"}], "description": "What."},
                "n": {"type": "integer", "default": 3, "description": "Count\nof things."}
            },
            "$defs": {
                "Mode": {"description": "A mode.", "oneOf": [
                    {"const": "a", "type": "string", "description": "First."},
                    {"const": "b", "type": "string", "description": "Second | other."}
                ]},
                "Target": {"description": "A target.", "oneOf": [
                    {"description": "Board.", "type": "object",
                     "properties": {"kind": {"const": "board", "type": "string"},
                                    "rows": {"type": "integer", "description": "Rows."}},
                     "required": ["kind", "rows"]}
                ]}
            }
        });
        let md = render(&schema);
        // Required first, with links to the definitions.
        assert!(md.contains("| `mode` | [Mode](#mode) | yes |"));
        assert!(md.contains("| `target` | [Target](#target) | no |"));
        // Soft-wrapped descriptions are joined; defaults get a column.
        assert!(md.contains("| `n` | integer | no | `3` | Count of things. |"));
        // Enumerations list their values; pipes are escaped.
        assert!(md.contains("| `b` | Second \\| other. |"));
        // Tagged unions list their variants without the tag field.
        assert!(md.contains("**`kind = \"board\"`**: Board."));
        assert!(md.contains("| `rows` | integer | yes | Rows. |"));
        assert!(md.contains("Unknown fields are rejected."));
        // Definitions follow the order of first mention.
        assert!(md.find("## Mode").unwrap() < md.find("## Target").unwrap());
    }
}
