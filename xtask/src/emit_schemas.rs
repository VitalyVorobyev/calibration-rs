/// The generated Python module, relative to the workspace root.
const PYTHON_TYPES: &str =
    "crates/vision-calibration-py/python/vision_calibration/_generated_types.py";

/// Its header: a do-not-edit notice and the module docstring.
const PYTHON_HEADER: &str = r#"# Generated by `cargo xtask emit-schemas` from the JSON Schemas of the Rust
# types; do not edit. `cargo xtask emit-schemas --check` fails when this file
# is stale.
"""Serde payload shapes of the Rust configuration, input and export types.

Each ``TypedDict`` here is the JSON form of the Rust type of the same name: a
configuration as the library reads it, an input dataset, and an export or
report as a workflow returns it. A key outside ``required`` in the schema is
optional (``total=False``). An enum with data is a union of one ``TypedDict``
per variant, named ``<Enum>_<Variant>``.

Most code uses the dataclasses of :mod:`vision_calibration.models`; these
types describe the raw payloads their ``to_payload``/``from_payload``
methods exchange with the Rust extension.
"""
"#;

/// `$defs` names replaced in every schema rendered as Python: the schema
/// proxy of a Rust type carries the proxy's name.
const PYTHON_RENAMES: &[(&str, &str)] = &[("Iso3Schema", "Iso3")];

/// A schema written to disk and, when `python` names its root type, rendered
/// as Python.
struct Emitted {
    /// File stem.
    name: &'static str,
    schema: Value,
    /// The type's `Default` value, written beside the schema.
    default: Option<Value>,
    python: Option<Python>,
}

/// How a schema's types are named in Python.
struct Python {
    /// The root type: the Rust name of the type.
    root: &'static str,
    /// A generic Rust type has one `$defs` name for every instantiation; each
    /// is renamed to the Rust alias of the instantiation.
    renames: &'static [(&'static str, &'static str)],
}

pub fn run(workspace_root: &Path, check: bool) -> Result<()> {
    let app_dir = workspace_root.join("app/src/schemas");
    let api_dir = workspace_root.join("schemas");
    let suite_dir = workspace_root.join("regression/schema");

    let app = vec![
        Emitted {
            name: "dataset_spec",
            schema: schema_value::<DatasetSpec>(),
            default: None,
            python: None,
        },
        config::<PlanarIntrinsicsConfig>("planar_intrinsics_config", "PlanarIntrinsicsConfig"),
        config::<SingleCamHandeyeConfig>("single_cam_handeye_config", "SingleCamHandeyeConfig"),
        config::<LaserlineDeviceConfig>("laserline_device_config", "LaserlineDeviceConfig"),
        config::<RigExtrinsicsConfig>("rig_extrinsics_config", "RigExtrinsicsConfig"),
        config::<RigHandeyeConfig>("rig_handeye_config", "RigHandeyeConfig"),
        config::<RigHandeyeLaserlineConfig>(
            "rig_handeye_laserline_config",
            "RigHandeyeLaserlineConfig",
        ),
        config::<RigLaserlineDeviceConfig>(
            "rig_laserline_device_config",
            "RigLaserlineDeviceConfig",
        ),
    ];
    let api = vec![
        reads::<PlanarIntrinsicsInput>(
            "planar_intrinsics_input",
            "PlanarIntrinsicsInput",
            &[("View", "PlanarView")],
        ),
        reads::<SingleCamHandeyeInput>(
            "single_cam_handeye_input",
            "SingleCamHandeyeInput",
            &[("View", "SingleCamHandeyeView")],
        ),
        reads::<LaserlineDeviceInput>(
            "laserline_device_input",
            "LaserlineDeviceInput",
            &[("View", "LaserlineView")],
        ),
        reads::<RigExtrinsicsInput>(
            "rig_extrinsics_input",
            "RigExtrinsicsInput",
            &[("RigView", "RigExtrinsicsView")],
        ),
        reads::<RigHandeyeInput>(
            "rig_handeye_input",
            "RigHandeyeInput",
            &[("RigView", "RigHandeyeView")],
        ),
        reads::<RigLaserlineDeviceInput>(
            "rig_laserline_device_input",
            "RigLaserlineDeviceInput",
            &[],
        ),
        reads::<RigHandeyeLaserlineInput>(
            "rig_handeye_laserline_input",
            "RigHandeyeLaserlineInput",
            &[],
        ),
        writes::<PlanarIntrinsicsExport>("planar_intrinsics_export", "PlanarIntrinsicsExport"),
        writes::<SingleCamHandeyeExport>("single_cam_handeye_export", "SingleCamHandeyeExport"),
        writes::<LaserlineDeviceExport>("laserline_device_export", "LaserlineDeviceExport"),
        writes::<RigExtrinsicsExport>("rig_extrinsics_export", "RigExtrinsicsExport"),
        writes::<RigHandeyeExport>("rig_handeye_export", "RigHandeyeExport"),
        writes::<RigLaserlineDeviceExport>(
            "rig_laserline_device_export",
            "RigLaserlineDeviceExport",
        ),
        writes::<RigHandeyeLaserlineExport>(
            "rig_handeye_laserline_export",
            "RigHandeyeLaserlineExport",
        ),
        reads::<QualityThresholds>("quality_thresholds", "QualityThresholds", &[]),
        writes::<QualityReport>("quality_report", "QualityReport"),
        writes::<ProjectionUncertainty>("projection_uncertainty", "ProjectionUncertainty"),
    ];
    let suite = vec![
        plain("observation_set", schema_value::<ObservationSet>()),
        plain("truth", schema_value::<Truth>()),
        plain("external_result", schema_value::<ExternalResult>()),
    ];

    let mut drift = Vec::new();
    let mut files = 0;

    // The manifest field reference in the book, rendered from the schema.
    write_text_or_check(
        &workspace_root.join("book/src/manifest_reference.md"),
        &manifest_doc::render(&app[0].schema),
        check,
        &mut drift,
    )?;
    files += 1;

    for (dir, emitted) in [(&app_dir, &app), (&api_dir, &api), (&suite_dir, &suite)] {
        if !check {
            std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
        }
        for entry in emitted {
            write_or_check(
                &dir.join(format!("{}.json", entry.name)),
                &entry.schema,
                check,
                &mut drift,
            )?;
            files += 1;
            if let Some(default) = &entry.default {
                write_or_check(
                    &dir.join(format!("{}.default.json", entry.name)),
                    default,
                    check,
                    &mut drift,
                )?;
                files += 1;
            }
        }
    }

    // The Python payload types, rendered from the config, input, export and
    // quality schemas.
    let python: Vec<PySchema<'_>> = app
        .iter()
        .chain(&api)
        .filter_map(|entry| {
            entry.python.as_ref().map(|python| PySchema {
                source: entry.name,
                root: python.root,
                schema: &entry.schema,
                renames: python.renames,
            })
        })
        .collect();
    let module = py_types::render(PYTHON_HEADER, &python, PYTHON_RENAMES)
        .context("rendering the Python payload types")?;
    write_text_or_check(
        &workspace_root.join(PYTHON_TYPES),
        &module,
        check,
        &mut drift,
    )?;
    files += 1;

    if check {
        if drift.is_empty() {
            println!("generated files up to date ({files} files)");
            Ok(())
        } else {
            for entry in &drift {
                entry.report();
            }
            let hint = if drift.iter().any(|d| matches!(d, Drift::LineEndings(_))) {
                "; the CRLF ones need an LF checkout (`git add --renormalize .`), not a re-emit"
            } else {
                ""
            };
            bail!(
                "{} generated file(s) out of date; run `cargo xtask emit-schemas` and commit the result{hint}",
                drift.len()
            )
        }
    } else {
        println!(
            "emitted {files} files to {}, {}, {} and {PYTHON_TYPES}",
            app_dir.display(),
            api_dir.display(),
            suite_dir.display()
        );
        Ok(())
    }
}

/// A config type's schema and its `Default` value — the app's form tests
/// round-trip the latter through the former.
fn config<T: JsonSchema + Default + Serialize>(name: &'static str, root: &'static str) -> Emitted {
    let default = serde_json::to_value(T::default()).expect("a config serialises to JSON");
    Emitted {
        name,
        schema: schema_value::<T>(),
        default: Some(default),
        python: Some(Python { root, renames: &[] }),
    }
}

/// The schema of a type a workflow reads: what deserializes.
fn reads<T: JsonSchema>(
    name: &'static str,
    root: &'static str,
    renames: &'static [(&'static str, &'static str)],
) -> Emitted {
    Emitted {
        name,
        schema: schema_value::<T>(),
        default: None,
        python: Some(Python { root, renames }),
    }
}

/// The schema of a type a workflow returns: what serializes, so a field that
/// is always written is required.
fn writes<T: JsonSchema>(name: &'static str, root: &'static str) -> Emitted {
    let schema = SchemaSettings::draft2020_12()
        .for_serialize()
        .into_generator()
        .into_root_schema_for::<T>();
    Emitted {
        name,
        schema: serde_json::to_value(schema).expect("JsonSchema serialization is infallible"),
        default: None,
        python: Some(Python { root, renames: &[] }),
    }
}

fn plain(name: &'static str, schema: Value) -> Emitted {
    Emitted {
        name,
        schema,
        default: None,
        python: None,
    }
}

fn schema_value<T: JsonSchema>() -> Value {
    serde_json::to_value(schema_for!(T)).expect("JsonSchema serialization is infallible")
}

/// Why a committed file no longer matches what the generator produces.
enum Drift {
    /// The file is missing, or its content genuinely differs — a type changed
    /// and the file was not re-emitted.
    Stale(PathBuf),
    /// The content matches once CRLF is normalized: the working copy was
    /// checked out with the wrong line endings, not left stale. Re-emitting
    /// fixes nothing — `.gitattributes`' `eol=lf` rule is what prevents this.
    LineEndings(PathBuf),
}

impl Drift {
    fn report(&self) {
        match self {
            Self::Stale(path) => eprintln!("drift: {}", path.display()),
            Self::LineEndings(path) => {
                eprintln!("line-ending drift (CRLF on disk): {}", path.display());
            }
        }
    }
}

fn write_or_check(path: &Path, schema: &Value, check: bool, drift: &mut Vec<Drift>) -> Result<()> {
    let mut text =
        serde_json::to_string_pretty(schema).context("rendering schema as pretty JSON")?;
    text.push('\n');
    write_text_or_check(path, &text, check, drift)
}

fn write_text_or_check(path: &Path, text: &str, check: bool, drift: &mut Vec<Drift>) -> Result<()> {
    let mut text = text.to_string();
    if !text.ends_with('\n') {
        text.push('\n');
    }

    if check {
        let on_disk = match std::fs::read_to_string(path) {
            Ok(s) => s,
            Err(_) => {
                drift.push(Drift::Stale(path.to_path_buf()));
                return Ok(());
            }
        };
        if on_disk != text {
            drift.push(if on_disk.replace("\r\n", "\n") == text {
                Drift::LineEndings(path.to_path_buf())
            } else {
                Drift::Stale(path.to_path_buf())
            });
        }
        return Ok(());
    }

    std::fs::write(path, &text).with_context(|| format!("writing {}", path.display()))?;
    Ok(())
}
