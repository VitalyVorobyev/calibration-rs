//! Emit JSON Schemas for the workspace's serialized types, and the files
//! generated from them.
//!
//! - Config schemas go to `app/src/schemas/<name>.json`, plus
//!   `<name>.default.json` (the type's `Default` value) for every config that
//!   has one. The Tauri app reads the schemas at build time to drive
//!   schema-driven forms in the Run workspace; the defaults feed the app's
//!   form round-trip tests.
//! - The input, export and quality schemas — what a workflow reads and what
//!   it returns — go to `schemas/<name>.json`, for tools that consume the
//!   results. Inputs and thresholds describe what deserializes, exports and
//!   reports what serializes.
//! - The suite's observation, truth and external-result formats go to
//!   `regression/schema/<name>.json`, for authors of comparison harnesses.
//! - The dataset manifest's schema is rendered as the book's field reference,
//!   `book/src/manifest_reference.md` (see `manifest_doc`).
//! - The config, input, export and quality schemas are rendered as the Python
//!   package's `TypedDict`s, `_generated_types.py` (see `py_types`).
//!
//! With `--check`, the command instead verifies that the files on disk match
//! what would be generated from current source. CI runs this to catch drift
//! between source and committed files.

